# Builds the Windows installer: dist\TelegramForClaude-Setup-<version>.exe
#
#   powershell -ExecutionPolicy Bypass -File packaging\build.ps1
#
# Reads build.env from the project root (see packaging\build.env.example) to bake
# the app's Telegram API ID into the program. Without it the build still works,
# but every user must enter their own API ID on the settings page.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$version = (Select-String -Path "src\telegram_mcp\__init__.py" -Pattern '__version__ = "(.+)"').Matches[0].Groups[1].Value
Write-Host "Version $version"

# --- the baked-in API ID (never committed: src\telegram_mcp\_embedded.py is in .gitignore)
$embedded = "src\telegram_mcp\_embedded.py"
$values = @{}
if (Test-Path "build.env") {
    foreach ($line in Get-Content "build.env") {
        if ($line -match '^\s*([A-Z_]+)\s*=\s*(.*)\s*$') { $values[$Matches[1]] = $Matches[2] }
    }
}
$apiId = $values["TELEGRAM_BUILD_API_ID"]
$apiHash = $values["TELEGRAM_BUILD_API_HASH"]
$readOnly = if ($values["TELEGRAM_BUILD_READ_ONLY_DEFAULT"] -eq "false") { "False" } else { "True" }
if ($apiId -and $apiHash) {
    Write-Host "Baking in API ID $apiId (read-only by default: $readOnly)"
} else {
    Write-Warning "build.env has no API ID: users will have to enter their own."
    $apiId = "0"; $apiHash = ""
}
$content = "# Generated by packaging/build.ps1 for one build, then deleted. Never commit.`n" +
    "API_ID = $apiId`nAPI_HASH = `"$apiHash`"`nREAD_ONLY_DEFAULT = $readOnly`n"
[IO.File]::WriteAllText((Join-Path $root $embedded), $content, (New-Object Text.UTF8Encoding $false))

try {
    uv sync --extra build --extra dev
    if ($LASTEXITCODE -ne 0) { throw "uv sync failed" }

    # --- the program: a folder with TelegramForClaude.exe and its libraries
    uv run --no-sync pyinstaller packaging\entry.py `
        --name TelegramForClaude `
        --onedir --console --noconfirm --clean `
        --distpath dist --workpath build `
        --paths src `
        --add-data "src\telegram_mcp\app\page.html;telegram_mcp\app" `
        --hidden-import telegram_mcp._embedded `
        --collect-submodules uvicorn `
        --collect-submodules telegram_mcp `
        --collect-data mcp `
        --copy-metadata mcp `
        --log-level WARN
    if ($LASTEXITCODE -ne 0) { throw "PyInstaller failed" }
} finally {
    # The dev environment must not pick up the friends' API ID or read-only default.
    Remove-Item -Force (Join-Path $root $embedded) -ErrorAction SilentlyContinue
}

# --- smoke test: the program starts and answers as an MCP server
$exe = "dist\TelegramForClaude\TelegramForClaude.exe"
$out = & $exe --help
if ($LASTEXITCODE -ne 0) { throw "The built program does not start" }

# --- the installer (Inno Setup reads the script as UTF-8 only with a BOM)
$iss = "packaging\installer.iss"
$text = [IO.File]::ReadAllText((Join-Path $root $iss))
[IO.File]::WriteAllText((Join-Path $root $iss), $text, (New-Object Text.UTF8Encoding $true))
$iscc = "C:\Program Files (x86)\Inno Setup 6\ISCC.exe"
if (-not (Test-Path $iscc)) { throw "Inno Setup 6 is not installed: https://jrsoftware.org/isdl.php" }
& $iscc /Q "/DAppVersion=$version" "/DSourceDir=..\dist\TelegramForClaude" $iss
if ($LASTEXITCODE -ne 0) { throw "Inno Setup failed" }

$setup = "dist\TelegramForClaude-Setup-$version.exe"
$size = [math]::Round((Get-Item $setup).Length / 1MB, 1)
Write-Host "Done: $setup ($size MB)"
